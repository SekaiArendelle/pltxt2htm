SYMBOL_ROOT = ROOT / "include" / "pltxt2htm" / "details" / "symbols"


@dataclasses.dataclass(frozen=True)
class Symbol:
    export_name: str
    local_name: str
    return_type: str
    parameters: tuple[str, ...]
    nodiscard: bool = False


@dataclasses.dataclass(frozen=True)
class Library:
    api: str
    name: str
    namespace: str
    macro_prefix: str
    symbols: tuple[Symbol, ...]


